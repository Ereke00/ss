import spacy
import numpy as np

# Загрузка модели spaCy
nlp = spacy.load("en_core_web_md")  # или другая подходящая модель

# Пример текста для сравнения
text1 = "авторами рассматривается понятие искусственного интеллекта и странно законодателя до старинные и определяется раскрывается проблема про субъектно искусственного интеллекта как объекта субъекта субъектов ограничены по всем деятельности всё"
text2 = "Авторами статьи отмечается огромное внимание последние годы уделяется исследованиям возможностей искусственного интеллекта."

# Получение векторов для текстов
vector1 = nlp(text1).vector
vector2 = nlp(text2).vector

# Измерение схожести (косинусное сходство)
similarity_score = np.dot(vector1, vector2) / (np.linalg.norm(vector1) * np.linalg.norm(vector2))
print(f"Схожесть текстов: {similarity_score}")
